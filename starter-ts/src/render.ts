/** PLAN.md: the same plan as plan.json, in the order a partner reads it. Every cited id is printed with what it is. */
import type { EngineResult } from "./engine";
import { gbp } from "./file";
import { LEVEL_RANK } from "./programme";
import { ALSO_RESPONDS } from "./select";

const LEVEL_MARK: Record<string, string> = {
  significant: "**SIGNIFICANT**",
  elevated: "elevated",
  baseline: "baseline",
  notApplicable: "n/a",
};

export function renderPlan({ plan, file, programme, evidence }: EngineResult): string {
  const c = file.company,
    e = c.engagement,
    b = plan.budget;
  const cited = new Set<string>();
  const cite = (ids: string[]) => {
    ids.forEach((i) => cited.add(i));
    return ids.length ? ` [${ids.join(", ")}]` : "";
  };
  const title = (id: string) => programme.procedures.find((p) => p.id === id)!.title;
  const L: string[] = [];
  const sig = plan.areas.filter((a) => a.level === "significant");
  L.push(`# Audit plan: ${c.name}, FY ending ${c.financialYear.end}`, "");
  L.push(
    `Engagement partner ${e.partner}. ${e.firstYear ? "First-year audit." : `Year ${e.yearsAsAuditor} as auditors.`} Materiality ${gbp(e.materialityMinor.overall)}, performance ${gbp(e.materialityMinor.performance)}, clearly trivial ${gbp(e.materialityMinor.clearlyTrivial)}.`,
    "",
  );
  L.push(
    `**Hours: ${b.totalHours}h planned against a ${b.budgetHours}h budget${b.gapHours > 0 ? ` — ${b.gapHours}h over. Nothing has been cut to fit; see Budget.` : b.gapHours < 0 ? `, ${-b.gapHours}h under.` : "."}** Mandatory procedures account for ${b.mandatoryHours}h.`,
    "",
  );
  L.push(
    `**Significant risks (${sig.length}):** ${sig.map((a) => `${a.area} (${a.assertions.join(", ")})`).join("; ") || "none"}.`,
    "",
  );
  L.push(
    `Generated by the planning engine, ruleset ${plan.rulesetVersion}, from the file's inputs (hashes in plan.json). Planning notes read through ${plan.notesExtraction.file}.`,
    "",
  );

  L.push(
    "## Risk by area",
    "",
    "Hours are counted once, under the procedure's own area; a procedure in brackets also responds to that area. The column sums to the plan total.",
    "",
    "| Area | Level | Assertions at risk | Selected | Hours |",
    "|---|---|---|---|---|",
  );
  const order = [...plan.areas].sort(
    (a, b) =>
      LEVEL_RANK[b.level] - LEVEL_RANK[a.level] ||
      programme.procedures.findIndex((p) => p.area === a.area) -
        programme.procedures.findIndex((p) => p.area === b.area),
  );
  for (const a of order) {
    const sel = plan.procedures.filter((p) => p.area === a.area && p.selected);
    const also =
      a.level === "notApplicable"
        ? []
        : plan.procedures.filter(
            (p) => p.selected && p.area !== a.area && (ALSO_RESPONDS[p.procedureId] ?? []).includes(a.area),
          );
    const ids = [...sel.map((p) => p.procedureId), ...also.map((p) => `(${p.procedureId})`)];
    L.push(
      `| ${a.area} | ${LEVEL_MARK[a.level]} | ${a.assertions.join(", ") || "—"} | ${ids.join(", ") || "—"} | ${sel.reduce((s, p) => s + p.hours, 0)} |`,
    );
  }
  L.push("");

  for (const a of order) {
    L.push(`## ${a.area}: ${LEVEL_MARK[a.level]}`, "");
    if (a.level === "notApplicable") {
      L.push(`Not in scope: ${a.scopeReason}.${cite(a.scopeEvidence)}`, "");
    } else {
      if (a.rules.length) L.push(`Rules: ${a.rules.join("; ")}.`, "");
      const raising = a.sources.filter((s) => s.severity !== "info");
      if (raising.length) {
        L.push("Why:", "");
        for (const s of raising.sort(
          (x, y) => LEVEL_RANK[y.severity] - LEVEL_RANK[x.severity] || x.kind.localeCompare(y.kind),
        ))
          L.push(
            `- *${s.kind}${s.severity === "significant" ? ", significant" : ""}* — ${s.text}${s.assertions.length ? ` (${s.assertions.join(", ")})` : ""}.${cite(s.evidenceIds)}`,
          );
        L.push("");
      } else L.push("Why: nothing in the file raises this area above baseline.", "");
      const ctx = [...a.sources.filter((s) => s.severity === "info"), ...a.mitigating];
      if (ctx.length) {
        L.push("Also considered, not raising the level:", "");
        for (const s of ctx) L.push(`- ${s.text}.${cite(s.evidenceIds)}`);
        L.push("");
      }
    }
    const procs = plan.procedures.filter((p) => p.area === a.area);
    const also = plan.procedures.filter((p) => p.selected && (ALSO_RESPONDS[p.procedureId] ?? []).includes(a.area));
    if (also.length && a.level !== "notApplicable") {
      L.push("Also responding (from another area):", "");
      for (const p of also)
        L.push(
          `- **${p.procedureId} ${title(p.procedureId)}** — ${p.hours}h${p.extent ? `; extent: ${p.extent}` : ""} (listed under ${p.area})`,
        );
      L.push("");
    }
    const sel = procs.filter((p) => p.status === "selected"),
      om = procs.filter((p) => p.status === "omitted"),
      na = procs.filter((p) => p.status === "notApplicable");
    if (sel.length) {
      L.push("Selected:", "");
      for (const p of sel)
        L.push(
          `- **${p.procedureId} ${title(p.procedureId)}** — ${p.hours}h${p.extent ? `; extent: ${p.extent}` : ""}. ${p.reason}${cite(p.evidenceIds)}`,
        );
      L.push("");
    }
    if (om.length) {
      L.push("Not selected:", "");
      for (const p of om) L.push(`- ${p.procedureId} ${title(p.procedureId)} — ${p.reason}${cite(p.evidenceIds)}`);
      L.push("");
    }
    if (na.length) {
      L.push("Not applicable:", "");
      for (const p of na) L.push(`- ${p.procedureId} ${title(p.procedureId)} — ${p.reason}${cite(p.evidenceIds)}`);
      L.push("");
    }
  }

  L.push(
    "## Budget",
    "",
    `${b.totalHours}h planned, ${b.budgetHours}h budgeted, ${b.mandatoryHours}h of it mandatory.`,
  );
  if (b.gapHours > 0) {
    L.push(
      "",
      `The plan is ${b.gapHours}h over. The engine does not cut to fit. If the partner decides to defer, these are the non-mandatory procedures in order from lowest assessed risk, with what each loses:`,
      "",
    );
    for (const d of b.deferrable.slice(0, 10)) L.push(`- ${d.procedureId} (${d.hours}h): ${d.consequence}`);
  }
  L.push("");
  L.push("## Questions for the partner", "", ...plan.questions.map((q) => `- ${q}`), "");
  L.push("## Limitations", "", ...plan.limitations.map((q) => `- ${q}`), "");
  L.push("## Evidence cited", "", ...[...cited].sort().map((id) => `- \`${id}\` ${evidence.get(id)}`), "");
  return L.join("\n");
}
